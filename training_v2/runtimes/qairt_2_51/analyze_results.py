"""Validate collected MobileNet outputs and QNN accelerator evidence."""
import argparse,csv,hashlib,io,json,re,statistics,sys
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT.parents[1]/'host'))
from adb_transport import local_path
def profile_rows(path):
    lines=path.read_text(encoding="utf-8-sig").splitlines()
    start=next(i for i,line in enumerate(lines) if line.startswith("Msg Timestamp,"))
    return [{str(k).strip():str(v).strip() for k,v in row.items() if k is not None} for row in csv.DictReader(io.StringIO("\n".join(lines[start:])))]
def summarize(evidence):
    evidence=local_path(evidence)
    record=json.loads((evidence/"test-run.json").read_text(encoding="utf-8"))
    target=evidence/"target"/record["result_id"]
    labels=(ROOT/"assets/model/mobilenet_v2-qnn_dlc-w8a8/labels.txt").read_text(encoding="utf-8-sig").splitlines()
    if len(labels)!=1000:raise ValueError("Expected 1000 ImageNet labels")
    result={"runtime_version":"2.51.40.260930230134","model":"Qualcomm AI Hub MobileNet V2 w8a8","model_release":"v0.65.0","dlc_compiler_version":"2.50.0.260828221209","image":"PyTorch Hub dog.jpg","expected_top1":{"class_id":258,"label":"Samoyed"},"runs_requested":record["runs"],"originals_unchanged":record["originals_unchanged"],"backends":{}}
    arrays={}
    for backend in ("cpu","htp"):
        folder=target/backend
        paths=sorted(folder.glob("Result_*/*.raw"))
        if not paths:raise ValueError("Missing "+backend+" outputs")
        # Python opens long Windows paths; NumPy's filename-based C IO may not.
        samples=[np.frombuffer(p.read_bytes(),dtype="<f4") for p in paths]
        if any(a.shape!=(1000,) or not np.isfinite(a).all() for a in samples):raise ValueError("Invalid classifier output")
        a=samples[0].astype(np.float64);arrays[backend]=a
        probs=np.exp(a-a.max());probs/=probs.sum()
        top=np.argsort(a)[-5:][::-1]
        rows=profile_rows(folder/"profile.csv")
        events=[r for r in rows if r.get("Message")=="EXECUTE"]
        timings=[float(r["Time"])/1000 for r in events if r.get("Timing Source")=="NETRUN" and r.get("Event Level")=="ROOT" and r.get("Unit of Measurement")=="US"]
        if len(timings)!=record["runs"]:raise ValueError("Profile inference count mismatch")
        meta=(folder/"execution_metadata.yaml").read_text(encoding="utf-8")
        count=int(re.search(r"inferences_completed:\s*(\d+)",meta).group(1))
        accel=[r for r in events if r.get("Event Identifier")=="QNN accelerator (execute) time"]
        cycles=[r for r in events if r.get("Unit of Measurement")=="CYCLES" and r.get("Event Level")=="SUB-EVENT" and float(r["Time"])>0]
        top1s=[int(np.argmax(s)) for s in samples]
        result["backends"][backend]={"completed":count,"outputs_saved":len(paths),"top5":[{"class_id":int(i),"label":labels[i],"logit":float(a[i]),"softmax_probability":float(probs[i])} for i in top],"all_saved_top1_samoyed":all(i==258 for i in top1s),"saved_outputs_bitwise_identical":all(np.array_equal(samples[0],s) for s in samples),"netrun_execution_ms":{"samples":timings,"mean":statistics.mean(timings),"median":statistics.median(timings),"min":min(timings),"max":max(timings)},"profiling_accelerator_events":len(accel),"positive_per_operator_cycle_events":len(cycles),"scope":"Execution time reported by qnn-net-run profiling; no warmup or controlled performance benchmark","output_sha256":[hashlib.sha256(p.read_bytes()).hexdigest() for p in paths]}
        if not all(i==258 for i in top1s):raise ValueError(backend+" did not classify the reference image as Samoyed")
        if backend=="htp" and (not accel or not cycles):raise ValueError("No HTP accelerator/operator profiling evidence")
    diff=arrays["cpu"]-arrays["htp"]
    p0=np.exp(arrays["cpu"]-arrays["cpu"].max());p0/=p0.sum()
    p1=np.exp(arrays["htp"]-arrays["htp"].max());p1/=p1.sum()
    result["comparison"]={"top1_agrees":int(arrays["cpu"].argmax())==int(arrays["htp"].argmax()),"max_abs_logit_difference":float(abs(diff).max()),"rmse_logits":float(np.sqrt(np.mean(diff**2))),"max_abs_probability_difference":float(abs(p0-p1).max()),"strict_allclose_atol_1e-4_rtol_1e-3":bool(np.allclose(arrays["cpu"],arrays["htp"],atol=1e-4,rtol=1e-3)),"interpretation":"Same top-1 on this image; CPU and HTP scores are not numerically equivalent. This does not establish dataset accuracy."}
    result["status"]="PASS_RUNTIME_AND_SINGLE_IMAGE_CLASSIFICATION"
    result["limitations"]=["One reference image; not a dataset accuracy certification.","CPU and HTP probability vectors differ; strict numerical equivalence is not claimed.","Five or configured executions are a functional check, not a controlled speedup benchmark.","DLC generated by QAIRT 2.50 executed under runtime 2.51.40; this is the exact validated version combination.","No global installation, BSP or firmware update was performed."]
    (evidence/"results.json").write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8")
    text=["MobileNet V2 / QAIRT 2.51.40 - resultado da validacao","",result["status"],""]
    for b,row in result["backends"].items():
        top=row["top5"][0]
        text.append(f"{b.upper()}: {row['completed']} inferencias; {row['outputs_saved']} saidas salvas; top-1 {top['label']} ({100*top['softmax_probability']:.4f}%); media do perfil {row['netrun_execution_ms']['mean']:.4f} ms.")
    text+=["",f"Maior diferenca absoluta dos logits CPU/HTP: {result['comparison']['max_abs_logit_difference']:.8f}.","Top-1 coincide; os vetores de scores NAO sao equivalentes.","Tempo apenas informativo: sem aquecimento/controlar frequencias/condicoes termicas.","Bibliotecas originais preservadas: "+str(result["originals_unchanged"]),""]
    (evidence/"RESULTADOS.txt").write_text("\n".join(text),encoding="utf-8")
    print("\n".join(text))
    return result
def main():
    p=argparse.ArgumentParser();p.add_argument("--evidence",type=Path,required=True)
    a=p.parse_args();summarize(a.evidence)
if __name__=="__main__":main()

